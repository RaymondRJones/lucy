def _fallback(question: dict[str, Any]) -> Any:
    if question.get("ideal_answer") is not None:
        return question["ideal_answer"]
    answer_type = question["answer_type"]
    if answer_type == "boolean":
        return False
    if answer_type == "multi_select":
        return []
    if answer_type in {"entry_list", "address_list", "employment_history_list", "benefit_history_list"}:
        return []
    if answer_type == "address":
        return {}
    if answer_type == "number":
        return 0
    return ""


def build_full_coverage_i485_answers() -> dict[str, Any]:
    """Every I-485 question, answered from the persona or with the standard-path answer."""
    return {
        question["id"]: FULL_COVERAGE_I485_ANSWERS.get(question["id"], _fallback(question))
        for question in all_i485_questions()
    }


def full_coverage_answers() -> dict[str, Any]:
    """The persona's answers across all forms, keyed by question ID."""
    return {**build_full_coverage_i485_answers(), **FULL_COVERAGE_I485_ANSWERS, **FULL_COVERAGE_SHARED_ANSWERS}


def build_full_coverage_form_answers(form_key: str) -> dict[str, dict[str, Any]]:
    """Answers for one supplemental form, by questionnaire page."""
    answers = {**full_coverage_answers(), **FULL_COVERAGE_FORM_OVERRIDES.get(form_key, {})}
    pages: dict[str, dict[str, Any]] = {}
    for page in get_supplemental_form_config(form_key)["pages"]:
        pages[page["id"]] = {
            question["id"]: answers[question["id"]] if question["id"] in answers else _fallback(question)
            for question in page["questions"]
        }
    return pages
