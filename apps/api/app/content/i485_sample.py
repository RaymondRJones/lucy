def build_sample_i485_answers() -> dict[str, Any]:
    answers = dict(SAMPLE_I485_ANSWERS)
    for question in all_i485_questions():
        if question["id"] in answers:
            continue
        if question.get("ideal_answer") is not None:
            answers[question["id"]] = question["ideal_answer"]
        elif question["answer_type"] == "boolean":
            answers[question["id"]] = False
        elif question["answer_type"] == "number":
            answers[question["id"]] = 1
        elif question["answer_type"] == "date":
            answers[question["id"]] = "2000-01-01"
        elif question["answer_type"] == "multi_select":
            answers[question["id"]] = [question["options"][0]["value"]] if question.get("options") else []
        elif question["answer_type"] == "select":
            answers[question["id"]] = question["options"][0]["value"] if question.get("options") else ""
        elif question["required"]:
            answers[question["id"]] = "Sample response"
        else:
            answers[question["id"]] = ""
    return answers
